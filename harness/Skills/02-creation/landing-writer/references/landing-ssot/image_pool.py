def match_title(title):
    """Return category_key for the title, or 'generic' if no match."""
    tl = title.lower()
    for pat, cat in PATTERNS:
        if isinstance(pat, str):
            if pat in tl:
                return cat
        elif pat.search(tl):
            return cat
    return "generic"


def get_image(category="generic", idx=0):
    """Get image URL from pool by category and index (round-robin)."""
    urls = POOL.get(category, POOL["generic"])
    return urls[idx % len(urls)]


def assign_images_to_features(features, category=None):
    """Assign images to features list using round-robin."""
    for i, feat in enumerate(features):
        if not isinstance(feat, dict):
            continue
        cat = category or match_title(feat.get("title", ""))
        if "media" not in feat or not isinstance(feat.get("media"), dict):
            feat["media"] = {}
        feat["media"]["src"] = get_image(cat, i)
    return features


