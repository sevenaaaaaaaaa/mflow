def cfg():
    c = sp.sanity_cfg(); c["project"], c["dataset"] = PROJECT, DATASET; return c


def groq_retry(q, tries=5):
    for a in range(tries):
        try:
            url = "https://%s.api.sanity.io/v2024-01-01/data/query/%s?query=%s" % (
                cfg()["project"], cfg()["dataset"], urllib.parse.quote(q))
            req = urllib.request.Request(url, headers={"Authorization": "Bearer " + cfg()["token"]})
            return json.loads(urllib.request.urlopen(req, timeout=200).read())["result"]
        except Exception as e:
            print("retry", a, repr(e)[:90], flush=True)
            time.sleep(4 * (a + 1))
    raise RuntimeError("gave up")


