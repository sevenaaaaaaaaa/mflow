def check_banned(text, slug):
    issues = []
    for word in BANNED:
        if word.lower() in text.lower():
            issues.append(word)
    return issues

def write_blog(b):
    frontmatter = f"""---
slug: {b['slug']}
title: "{b['title']}"
description: "{b['description']}"
cover_url: "{COVER}"
alt_text: "{b['alt_text']}"
keywords: {str(b['keywords'])}
language: zh
category: {b['category']}
seo_title: "{b['seo_title']}"
seo_description: "{b['seo_description']}"
target_lp_slug: {b['target_lp_slug']}
content_cluster: {b['content_cluster']}
image_briefs: ["文章配图1", "文章配图2"]
---

"""
    content = frontmatter + b["body"].strip() + "\n"
    fp = os.path.join(OUT_DIR, f"{b['slug']}.md")
    with open(fp, "w", encoding="utf-8") as f:
        f.write(content)
    return fp

def main():
    print(f"Generating {len(BLOGS)} blogs...")
    issues = []
    for b in BLOGS:
        fp = write_blog(b)
        banned_hits = check_banned(b["body"], b["slug"])
        if banned_hits:
            issues.append(f"  ⚠️ {b['slug']}: banned phrase(s) -> {banned_hits}")
        print(f"  {b['slug']:50s} ✓ ({len(b['body'])} chars)")
    print(f"\nSuccessfully generated {len(BLOGS)} blogs")
    if issues:
        print(f"\n⚠️ Banned phrase issues found ({len(issues)}):")
        for i in issues:
            print(i)
    return len(BLOGS)

