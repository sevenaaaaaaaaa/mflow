def write_blog(b):
    frontmatter_lines = [
        "---",
        f'slug: {b["slug"]}',
        f'title: "{b["title"]}"',
        f'description: "{b["description"]}"',
        f'cover_url: "{COVER}"',
        f'alt_text: "{b["alt_text"]}"',
        f'keywords: {b["keywords"]}',
        "language: zh",
        f'category: {b["category"]}',
        f'seo_title: "{b["seo_title"]}"',
        f'seo_description: "{b["seo_description"]}"',
        f'target_lp_slug: {b["target_lp_slug"]}',
        "content_cluster: Zh-Batch4-Industry",
        'image_briefs: ["文章配图1", "文章配图2"]',
        "---",
    ]
    content = "\n".join(frontmatter_lines) + "\n\n" + b["body"]
    path = os.path.join(OUT_DIR, b["slug"] + ".md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return path


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    written = 0
    errors = []
    for i, b in enumerate(BLOGS):
        try:
            path = write_blog(b)
            written += 1
        except Exception as e:
            errors.append(f"Blog {i+1} ({b.get('slug', '?')}): {e}")
    print(f"Generated: {written} / {len(BLOGS)} files")
    for err in errors:
        print(f"  ERROR: {err}")
    if written > 0:
        print(f"\nSample file 1: {BLOGS[0]['slug']}.md")
        with open(os.path.join(OUT_DIR, BLOGS[0]["slug"] + ".md"), encoding="utf-8") as f:
            lines = f.readlines()
            print("".join(lines[:30]))
        mid = len(BLOGS) // 2
        print(f"\nSample file 2: {BLOGS[mid]['slug']}.md")
        with open(os.path.join(OUT_DIR, BLOGS[mid]["slug"] + ".md"), encoding="utf-8") as f:
            lines = f.readlines()
            print("".join(lines[:30]))
    return 0 if not errors else 1


